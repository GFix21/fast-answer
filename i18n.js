export function t(locale, key, ...args) {
  const loc = normalizeLocale(locale);
  const table = STRINGS[loc] || STRINGS.en;
  const v = table[key] ?? STRINGS.en[key] ?? key;
  return typeof v === "function" ? v(...args) : v;
}

