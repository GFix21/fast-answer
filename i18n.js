/** Fast Answer player-facing i18n. French is France (fr) or Quebec (fr-CA). */
export const LOCALES = ["en", "fr", "fr-CA", "de"];
export const LOCALE_LABELS = { en: "EN", fr: "France", "fr-CA": "Québec", de: "DE" };
export const LOCALE_KEY = "fa-locale";

const SPEECH = { en: "en-US", fr: "fr-FR", "fr-CA": "fr-CA", de: "de-DE" };

export function normalizeLocale(raw) {
  const text = String(raw || "en").trim().replace(/_/g, "-");
  if (/^fr-ca$/i.test(text)) return "fr-CA";
  const v = text.toLowerCase().slice(0, 2);
  return v === "fr" || v === "de" || v === "en" ? v : "en";
}

export function loadStoredLocale() {
  try {
    return normalizeLocale(localStorage.getItem(LOCALE_KEY) || "en");
  } catch {
    return "en";
  }
}

export function storeLocale(locale) {
  const loc = normalizeLocale(locale);
  try {
    localStorage.setItem(LOCALE_KEY, loc);
  } catch { /* ignore */ }
  return loc;
}

export function speechLang(locale) {
  return SPEECH[normalizeLocale(locale)] || "en-US";
}

/** Client bank URLs for the live game. */
export function questionsUrl(locale) {
  const loc = normalizeLocale(locale);
  if (loc === "en") return "./questions.json";
  return `./questions.${loc}.json`;
}

export function placementUrl(locale) {
  const loc = normalizeLocale(locale);
  if (loc === "en") return "./banks/placement/generational-first-pass.json";
  return `./banks/placement/${loc}/generational-first-pass.json`;
}

