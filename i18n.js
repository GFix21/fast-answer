export function t(locale, key, ...args) {
  const loc = normalizeLocale(locale);
  const table = loc === "fr-CA" ? STRINGS.fr : (STRINGS[loc] || STRINGS.en);
  const v = (loc === "fr-CA" ? QC_UI[key] : undefined) ?? table[key] ?? STRINGS.en[key] ?? key;
  return typeof v === "function" ? v(...args) : v;
}

export function languageSwitcherHtml(locale, { idPrefix = "lang" } = {}) {
  const cur = normalizeLocale(locale);
  return `<div class="lang-switch" role="group" aria-label="${t(cur, "language")}">
    ${LOCALES.map((loc) =>
      `<button type="button" class="lang-btn ${cur === loc ? "on" : ""}" data-locale="${loc}" id="${idPrefix}-${loc}">${LOCALE_LABELS[loc]}</button>`
    ).join("")}
  </div>`;
}
